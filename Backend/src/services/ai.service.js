const { GoogleGenAI } = require("@google/genai");
const { z } = require("zod");
const { zodToJsonSchema } = require("zod-to-json-schema");
const puppeteer = require("puppeteer");

const ai = new GoogleGenAI({
    apiKey: process.env.GOOGLE_GENAI_API_KEY,
});

const interviewReportSchema = z.object({
    matchScore: z
        .number()
        .describe(
            "A score between 0 and 100 indicating how well the candidate's profile matches the job description"
        ),

    technicalQuestions: z
        .array(
            z.object({
                question: z
                    .string()
                    .describe("The technical question that can be asked in the interview"),

                intention: z
                    .string()
                    .describe(
                        "The intention of interviewer behind asking this question"
                    ),

                answer: z
                    .string()
                    .describe(
                        "How to answer this question, what points to cover, what approach to take etc."
                    ),
            })
        )
        .describe(
            "Technical questions that can be asked in the interview along with their intention and how to answer them"
        ),

    behavioralQuestions: z
        .array(
            z.object({
                question: z
                    .string()
                    .describe("The behavioral question that can be asked in the interview"),

                intention: z
                    .string()
                    .describe(
                        "The intention of interviewer behind asking this question"
                    ),

                answer: z
                    .string()
                    .describe(
                        "How to answer this question, what points to cover, what approach to take etc."
                    ),
            })
        )
        .describe(
            "Behavioral questions that can be asked in the interview along with their intention and how to answer them"
        ),

    skillGaps: z
        .array(
            z.object({
                skill: z
                    .string()
                    .describe("The skill which the candidate is lacking"),

                severity: z
                    .enum(["low", "medium", "high"])
                    .describe(
                        "The severity of this skill gap, i.e. how important is this skill for the job and how much it can impact the candidate's chances"
                    ),
            })
        )
        .describe(
            "List of skill gaps in the candidate's profile along with their severity"
        ),

    preparationPlan: z
        .array(
            z.object({
                day: z
                    .number()
                    .describe(
                        "The day number in the preparation plan, starting from 1"
                    ),

                focus: z
                    .string()
                    .describe(
                        "The main focus of this day in the preparation plan, e.g. data structures, system design, mock interviews etc."
                    ),

                tasks: z
                    .array(z.string())
                    .describe(
                        "List of tasks to be done on this day to follow the preparation plan"
                    ),
            })
        )
        .describe(
            "A day-wise preparation plan for the candidate to follow in order to prepare for the interview effectively"
        ),

    title: z
        .string()
        .describe(
            "The title of the job for which the interview report is generated"
        ),
});


// ============================================================
// GENERATE INTERVIEW REPORT
// ============================================================

async function generateInterviewReport({
    resume,
    selfDescription,
    jobDescription,
}) {
    const prompt = `
Generate an interview report for a candidate with the following details:

Resume:
${resume}

Self Description:
${selfDescription}

Job Description:
${jobDescription}
`;

    const response = await ai.models.generateContent({
        model: "gemini-3-flash-preview",
        contents: prompt,
        config: {
            responseMimeType: "application/json",
            responseSchema: zodToJsonSchema(interviewReportSchema),
        },
    });

    return JSON.parse(response.text);
}


// ============================================================
// GENERATE PDF FROM HTML
// ============================================================

async function generatePdfFromHtml(htmlContent) {
    console.log("Starting Puppeteer PDF generation...");

    console.log(
        "Puppeteer executable path:",
        puppeteer.executablePath()
    );

    const browser = await puppeteer.launch({
        headless: true,

        executablePath: puppeteer.executablePath(),

        args: [
            "--no-sandbox",
            "--disable-setuid-sandbox",
            "--disable-dev-shm-usage",
            "--disable-gpu",
            "--no-first-run",
            "--no-zygote",
        ],
    });

    try {
        const page = await browser.newPage();

        await page.setContent(htmlContent, {
            waitUntil: "networkidle0",
        });

        const pdfBuffer = await page.pdf({
            format: "A4",
            printBackground: true,

            margin: {
                top: "20mm",
                bottom: "20mm",
                left: "15mm",
                right: "15mm",
            },
        });

        console.log("PDF generated successfully.");

        return pdfBuffer;
    } finally {
        await browser.close();

        console.log("Puppeteer browser closed.");
    }
}


// ============================================================
// GENERATE RESUME PDF
// ============================================================

async function generateResumePdf({
    resume,
    selfDescription,
    jobDescription,
}) {
    const resumePdfSchema = z.object({
        html: z
            .string()
            .describe(
                "The HTML content of the resume which can be converted to PDF using Puppeteer"
            ),
    });

    const prompt = `
Generate a professional resume for a candidate with the following details:

Resume:
${resume}

Self Description:
${selfDescription}

Job Description:
${jobDescription}

The response should be a JSON object with a single field "html"
which contains the HTML content of the resume.

Requirements:

1. Tailor the resume specifically to the given job description.
2. Highlight the candidate's strengths and relevant experience.
3. The content should sound human-written and professional.
4. Do not mention that the resume was generated by AI.
5. The HTML should be well-formatted and visually appealing.
6. Keep the design simple and professional.
7. Make the resume ATS friendly.
8. Make the resume easy for ATS systems to parse.
9. Do not unnecessarily add information that is not present in the candidate's details.
10. Keep the resume approximately 1-2 pages when converted to PDF.
11. Focus on quality rather than quantity.
12. Include relevant skills and experience that improve the candidate's chances of getting an interview.
`;

    const response = await ai.models.generateContent({
        model: "gemini-3-flash-preview",
        contents: prompt,

        config: {
            responseMimeType: "application/json",
            responseSchema: zodToJsonSchema(resumePdfSchema),
        },
    });

    const jsonContent = JSON.parse(response.text);

    if (!jsonContent || !jsonContent.html) {
        throw new Error("Gemini did not return valid resume HTML.");
    }

    const pdfBuffer = await generatePdfFromHtml(
        jsonContent.html
    );

    return pdfBuffer;
}


